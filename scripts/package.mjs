import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import assert from 'node:assert/strict';
import { zipSync, unzipSync } from 'fflate';
const root='plugins/elevenlabs-transcription';
const manifest=JSON.parse(readFileSync(`${root}/manifest.json`,'utf8'));
const filename=`${manifest.id}@${manifest.version}.zip`;
const entries={};
for(const [name,path] of Object.entries({'manifest.json':`${root}/manifest.json`,'index.js':`${root}/build/js/index.js`,'LICENSE':'LICENSE','NOTICE':'NOTICE','Apache-2.0.txt':'licenses/Apache-2.0.txt'})) entries[name]=[new Uint8Array(readFileSync(path)),{mtime:new Date('2026-01-01T00:00:00Z')}];
const bytes=zipSync(entries,{level:9});
const extracted=unzipSync(bytes);assert.deepEqual(Object.keys(extracted).sort(),['Apache-2.0.txt','LICENSE','NOTICE','index.js','manifest.json']);
for(const [name,[expected]] of Object.entries(entries))assert.deepEqual(extracted[name],expected);
assert.equal(manifest.dist.script,'index.js');assert.equal(manifest.dist.android,undefined);
mkdirSync('dist',{recursive:true});mkdirSync('build',{recursive:true});
writeFileSync(`dist/${filename}`,bytes);
const url=`https://github.com/Anezium/valenced-elevenlabs-transcription/releases/download/v${manifest.version}/${filename}`;
writeFileSync('build/releases.json',JSON.stringify([{file:`dist/${filename}`,url}]));
execFileSync(process.execPath,['vendor/cli/dist/main.js','generate-index','--releases','build/releases.json','--out','index.json'],{stdio:'inherit'});
const index=JSON.parse(readFileSync('index.json','utf8'));const plugin=index.plugins[manifest.id];
const artifact=plugin.versions[manifest.version];assert.equal(plugin.channels.latest,manifest.version);
assert.equal(artifact.size,bytes.length);const hash=createHash('sha256').update(bytes).digest('hex');assert.equal(artifact.sha256,hash);assert.equal(artifact.url,url);
writeFileSync('dist/SHA256SUMS',`${hash}  ${filename}\n`);
console.log(`ZIP structure/bytes and official index verified: ${filename}, ${bytes.length} bytes, SHA256 ${hash}`);
